// Embeds drizzle/*.sql into src/migrations.ts, so the migrations travel inside the bundled server code
// (no migrations folder to locate at runtime in the Docker image).
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.join(import.meta.dirname, '..', '..');
const journal = JSON.parse(await readFile(path.join(root, 'drizzle/meta/_journal.json'), 'utf8')) as {
  entries: { idx: number; tag: string }[];
};
const migrations = await Promise.all(
  journal.entries
    .sort((a, b) => a.idx - b.idx)
    .map(async ({ tag }) => ({
      tag,
      statements: (await readFile(path.join(root, 'drizzle', `${tag}.sql`), 'utf8'))
        .split('--> statement-breakpoint')
        .map((s) => s.trim())
        .filter(Boolean),
    })),
);
const body = `// Generated by \`pnpm -F @versiondrift/db generate\` from drizzle/ — do not edit.
export const MIGRATIONS: readonly { tag: string; statements: readonly string[] }[] = ${JSON.stringify(migrations, null, 2)};
`;
await writeFile(path.join(root, 'src/migrations.ts'), body);
console.log(`embedded ${migrations.length} migration(s)`);
